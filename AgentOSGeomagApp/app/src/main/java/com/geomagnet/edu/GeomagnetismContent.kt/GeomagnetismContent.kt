/**
 * 地磁知识库 —— 本应用全部科普内容的唯一数据源。
 *
 * 每个 [GeomagTopic] 对应一个 AgentOS Action：
 * - actionName 遵循 SDK 命名规范：com.company.module.ACTION_NAME（简名大写）
 * - desc       是让大模型理解“何时调用该 Action”的关键文本，务必具体
 * - sections   是界面展示的详细内容（小标题 + 正文）
 * - speechText 是 TTS 语音播报文本（连贯、口语化）
 *
 * 内容要点均已按公开科学资料核实（地磁场强度、IGRF-14、磁极漂移速度、
 * 布容–松山界限、张衡一号/Swarm 等）。
 */
data class GeomagTopic(
    val actionName: String,
    val title: String,
    val desc: String,
    val subtitle: String,
    val queryDemo: String,
    val sections: List<Pair<String, String>>,
    val speechText: String
) {
    /** 上报给大模型的页面感知信息（覆盖式更新，内容保持精简） */
    val interfaceInfo: String
        get() = buildString {
            append("当前页面：地磁知识讲解员。正在展示【$title】。")
            sections.forEach { (head, body) ->
                append("【$head】")
                append(body.take(100))
                append("。")
            }
        }
}

